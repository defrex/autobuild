export function stampCompatibility(
  classification: FactClassification,
  supplied?: unknown,
): CompatibilityMetadata {
  if (supplied === undefined) return { writerVersion: AUTOBUILD_VERSION, classification }
  const metadata = compatibilityMetadataSchema.parse(supplied)
  if (metadata.classification !== classification)
    throw new Error('event compatibility classification disagrees with catalog')
  return metadata
}
