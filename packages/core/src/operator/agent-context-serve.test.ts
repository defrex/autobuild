import { describe, expect, test } from 'bun:test'
import type { AgentContextRecord } from '../store/agent-context'
import {
  contextIndex,
  contextInstructions,
  contextPrompts,
  contextSource,
  promptLabel,
  readContextFile,
  type CanonicalSkillBundle,
  type ContextReadResult,
} from './agent-context-serve'

const COMMIT = 'c0ffee'.padEnd(40, '0')
const content = (text: string) => ({ oid: `oid-${text.length}`, bytes: text.length, text })

const OPERATE = [
  '---',
  'name: ab-operate',
  'description: Operate builds.',
  '---',
  '# Operate',
  'Run ab abort my-build, then ab done. See [spec](../ab-guide/references/spec-standard.md#x).',
].join('\n')
const SPEC = [
  '---',
  'name: ab-spec',
  'description: >',
  '  Write specs',
  '  carefully.',
  '---',
  'Use ab ticket create.',
].join('\n')

function seededRecord(overrides: Partial<AgentContextRecord> = {}): AgentContextRecord {
  return {
    version: 1,
    commit: COMMIT,
    baseBranch: 'main',
    skills: [
      {
        name: 'ab-operate',
        paths: ['.agents/skills/ab-operate', '.claude/skills/ab-operate'],
        files: [{ path: 'SKILL.md', ...content(OPERATE) }],
      },
      {
        name: 'ab-spec',
        paths: ['.agents/skills/ab-spec', '.claude/skills/ab-spec'],
        files: [{ path: 'SKILL.md', ...content(SPEC) }],
      },
      {
        name: 'ab-guide',
        paths: ['.agents/skills/ab-guide'],
        files: [
          { path: 'SKILL.md', ...content("---\ndescription: 'Guide''s text'\n---\nguide") },
          { path: 'references/spec-standard.md', ...content('standard') },
          { path: 'logo.png', oid: 'png', bytes: 2, base64: 'AAE=' },
        ],
      },
    ],
    instructions: [
      {
        paths: ['packages/x/AGENTS.md'],
        directory: 'packages/x',
        ...content('nested'),
        imports: [],
      },
      {
        paths: ['AGENTS.md', 'CLAUDE.md'],
        directory: '',
        ...content('Root rules. See @docs/rules.md'),
        imports: ['docs/rules.md'],
      },
    ],
    imports: [
      { path: 'docs/rules.md', importedBy: ['AGENTS.md'], ...content('rules'), imports: [] },
    ],
    links: [],
    omitted: [{ path: 'secret.md', reason: 'outside-repository' }],
    ...overrides,
  }
}

const bundle: CanonicalSkillBundle = {
  version: '9.9.9',
  skills: [
    { installName: 'ab-operate', files: [{ path: 'SKILL.md', content: OPERATE }] },
    {
      installName: 'ab-tickets',
      files: [{ path: 'SKILL.md', content: '---\ndescription: T\n---\n' }],
    },
  ],
}

function read(view: ReturnType<typeof contextSource>, path: string, from?: string) {
  const outcome = readContextFile(view, { path, ...(from !== undefined ? { from } : {}) })
  if (outcome.kind !== 'found') throw new Error(outcome.message)
  return outcome.result as ContextReadResult & { text: string }
}

describe('captured agent context', () => {
  const view = contextSource(seededRecord(), null)

  test('the index names skills, descriptions, instructions, imports and load order', () => {
    const index = contextIndex(view, 'https://github.com/acme/a')
    expect(index).toMatchObject({ source: 'captured', commit: COMMIT, baseBranch: 'main' })
    expect(index.skills.map((skill) => [skill.name, skill.description])).toEqual([
      ['ab-operate', 'Operate builds.'],
      ['ab-spec', 'Write specs carefully.'],
      ['ab-guide', "Guide's text"],
    ])
    expect(index.skills[2]!.files).toContain('.agents/skills/ab-guide/references/spec-standard.md')
    expect(index.instructions).toEqual([
      { path: 'AGENTS.md', aliases: ['CLAUDE.md'], scope: '', imports: ['docs/rules.md'] },
      { path: 'packages/x/AGENTS.md', aliases: [], scope: 'packages/x', imports: [] },
    ])
    expect(index.imports).toEqual([{ path: 'docs/rules.md', importedBy: ['AGENTS.md'] }])
    expect(index.load).toEqual({
      beforeOperating: ['.agents/skills/ab-operate/SKILL.md'],
      beforeTicketWork: ['.agents/skills/ab-spec/SKILL.md', 'AGENTS.md', 'packages/x/AGENTS.md'],
    })
  })

  test('a SKILL.md read carries the generated preamble, then the exact text', () => {
    const result = read(view, '.claude/skills/ab-operate/SKILL.md')
    expect(result.path).toBe('.agents/skills/ab-operate/SKILL.md')
    const [preamble, ...rest] = result.text.split('\n---\n')
    expect(rest.join('\n---\n')).toBe(OPERATE)
    expect(preamble).toContain('generated by the server')
    expect(preamble).toContain(`at commit ${COMMIT.slice(0, 12)}`)
    expect(preamble).toContain('- `ab abort` → `builds.control` (action: "abort")')
    expect(preamble).toContain('- `ab done` → no tool: build sessions only')
    expect(preamble).toContain(
      'the instructions win for this repository: `AGENTS.md`, `packages/x/AGENTS.md`',
    )
    // Relative links resolve against the requested alias.
    expect(result.links).toEqual([
      {
        href: '../ab-guide/references/spec-standard.md#x',
        path: '.agents/skills/ab-guide/references/spec-standard.md',
      },
    ])
  })

  test('relative links read with `from`; plain skill files and binaries get no preamble', () => {
    const reference = read(
      view,
      '../ab-guide/references/spec-standard.md#x',
      '.agents/skills/ab-spec/SKILL.md',
    )
    expect(reference).toMatchObject({ kind: 'skill-file', skill: 'ab-guide', text: 'standard' })
    const binary = readContextFile(view, { path: '.agents/skills/ab-guide/logo.png' })
    expect(binary).toMatchObject({ kind: 'found', result: { contentBase64: 'AAE=', links: [] } })
  })

  test('instructions and imports are framed as the repository’s own files', () => {
    const root = read(view, './CLAUDE.md')
    expect(root).toMatchObject({ path: 'AGENTS.md', kind: 'instructions', scope: '' })
    for (const line of [
      "is this repository's own agent instructions file",
      'written for agents working in a checkout',
      'apply to the tickets, specs and answers you write',
      'apply only inside the sandbox',
      'takes precedence over Autobuild skills',
    ])
      expect(root.text).toContain(line)
    expect(root.text.endsWith('\n---\nRoot rules. See @docs/rules.md')).toBe(true)
    expect(read(view, 'docs/rules.md').text).toContain('imported by `AGENTS.md`')
  })

  test('a missing path is not found, and an omitted one names its reason', () => {
    expect(readContextFile(view, { path: 'nope.md' })).toEqual({
      kind: 'not-found',
      message: 'no file "nope.md" in the captured agent context; call context.list',
    })
    expect(readContextFile(view, { path: '/secret.md' })).toMatchObject({
      message: expect.stringContaining('omitted it (outside-repository)'),
    })
  })
})

describe('canonical fallback', () => {
  test('the index and every preamble say canonical; instructions are absent', () => {
    const view = contextSource(null, bundle)
    const index = contextIndex(view, 'https://github.com/acme/new')
    expect(index).toMatchObject({
      source: 'canonical',
      commit: null,
      version: '9.9.9',
      instructions: [],
    })
    expect(index.notice).toContain('Autobuild 9.9.9; agent instructions are absent')
    const result = read(view, '.agents/skills/ab-operate/SKILL.md')
    expect(result.text).toContain('canonical skill bundled with Autobuild 9.9.9')
    expect(result.text).toContain('none captured')
  })
})

describe('server instructions', () => {
  const captured = contextIndex(contextSource(seededRecord(), null), 'https://github.com/acme/a')
  const canonical = contextIndex(contextSource(null, bundle), 'https://github.com/acme/new')

  test('the scoped form lists skills, instructions and the load-before rules', () => {
    const text = contextInstructions([{ repo: captured.repo, index: captured }], { scoped: true })
    expect(text).toContain('- ab-operate — Operate builds.')
    expect(text).toContain('`AGENTS.md` (repository root), `packages/x/AGENTS.md` (`packages/x`)')
    expect(text).toContain('Before operating, load `ab-operate`')
    expect(text).toContain(
      'Before filing or revising tickets, load `ab-spec` (`.agents/skills/ab-spec/SKILL.md`), the agent instructions above.',
    )
    expect(text).not.toContain('### ')
  })

  test('the deployment form labels each repository and renders failures', () => {
    const text = contextInstructions(
      [
        { repo: captured.repo, index: captured },
        { repo: canonical.repo, index: canonical },
        { repo: 'https://github.com/acme/down', error: 'boom' },
      ],
      { scoped: false },
    )
    expect(text).toContain('### https://github.com/acme/a')
    expect(text).toContain('Agent instructions: absent (no captured record).')
    expect(text).toContain('`ab-tickets` (`.agents/skills/ab-tickets/SKILL.md`)')
    expect(text).toContain(
      '### https://github.com/acme/down\nAgent context is unavailable right now',
    )
  })
})

describe('prompt identities', () => {
  const withOperate = (text: string, extra: AgentContextRecord['skills'] = []) =>
    seededRecord({
      skills: [
        {
          name: 'ab-operate',
          paths: ['.agents/skills/ab-operate'],
          files: [{ path: 'SKILL.md', ...content(text) }],
        },
        ...extra,
      ],
    })
  const dotted = 'https://github.com/acme/a.b'
  const underscored = 'https://github.com/acme/a_b'
  const other = 'https://github.com/acme/zed'
  const entries = [
    { repo: dotted, index: contextIndex(contextSource(withOperate('dot'), null), dotted) },
    {
      repo: underscored,
      index: contextIndex(contextSource(withOperate('under'), null), underscored),
    },
    {
      repo: other,
      index: contextIndex(
        contextSource(
          withOperate('zed', [
            {
              name: 'x',
              paths: ['.agents/skills/x'],
              files: [{ path: 'SKILL.md', ...content('a') }],
            },
            {
              name: 'x',
              paths: ['.claude/skills/x'],
              files: [{ path: 'SKILL.md', ...content('b') }],
            },
          ]),
          null,
        ),
        other,
      ),
    },
  ]

  test('colliding names are suffixed, unique and map back to their own skill', () => {
    expect(promptLabel(dotted)).toBe(promptLabel(underscored))
    const prompts = contextPrompts(entries, { scoped: false })
    const names = prompts.map((prompt) => prompt.name)
    expect(new Set(names).size).toBe(names.length)
    const operate = prompts.filter((prompt) => prompt.skill === 'ab-operate')
    const ab = operate.filter((prompt) => prompt.repo !== other)
    expect(ab.map((prompt) => prompt.name)).toEqual([
      expect.stringMatching(/^github_com_acme_a_b\.ab-operate~[0-9a-f]{12}$/),
      expect.stringMatching(/^github_com_acme_a_b\.ab-operate~[0-9a-f]{12}$/),
    ])
    expect(new Set(ab.map((prompt) => prompt.repo))).toEqual(new Set([dotted, underscored]))
    // A non-colliding skill keeps its readable name.
    expect(names).toContain('github_com_acme_zed.ab-operate')
    // Same-basename skills inside one repository are both suffixed.
    const xs = prompts.filter((prompt) => prompt.skill === 'x')
    expect(xs.map((prompt) => prompt.entry).sort()).toEqual([
      '.agents/skills/x/SKILL.md',
      '.claude/skills/x/SKILL.md',
    ])
    expect(xs.every((prompt) => prompt.name.startsWith('github_com_acme_zed.x~'))).toBe(true)
    // The same-label subset and any input order recompute identical names.
    const subset = contextPrompts(entries.slice(0, 2), { scoped: false })
    expect(subset).toEqual(prompts.filter((prompt) => prompt.repo !== other))
    expect(contextPrompts([...entries].reverse(), { scoped: false })).toEqual(prompts)
  })
})

describe('the context tools through the registry', () => {
  test('a captured record is served without loading the canonical bundle', async () => {
    const { MemoryBuildStore } = await import('../store/memory')
    const { AGENT_CONTEXT_ARTIFACT, encodeAgentContext } = await import('../store/agent-context')
    const { buildRegistry, RegistryError } = await import('./registry')
    const store = new MemoryBuildStore()
    const repo = 'https://github.com/acme/a'
    let loads = 0
    const canonicalSkills = async () => {
      loads++
      return bundle
    }
    const registry = buildRegistry({ store, canonicalSkills })
    await store.ensureRepo(repo)

    const fallback = (await registry.call('context.list', { repo })) as { source: string }
    expect(fallback.source).toBe('canonical')
    expect(loads).toBe(1)

    const encoded = encodeAgentContext(seededRecord())
    await store.putRepoArtifact(repo, {
      kind: AGENT_CONTEXT_ARTIFACT,
      content: encoded.content,
      metadata: { digest: encoded.digest },
    })
    const listed = (await registry.call('context.list', { repo })) as { source: string }
    expect(listed.source).toBe('captured')
    const skill = (await registry.call('context.read', {
      repo,
      path: '.agents/skills/ab-operate/SKILL.md',
    })) as { text: string }
    expect(skill.text).toContain('`ab abort` → `builds.control`')
    expect(loads).toBe(1)

    const missing = await registry.call('context.read', { repo, path: 'nope.md' }).catch((e) => e)
    expect(missing).toBeInstanceOf(RegistryError)
    expect((missing as InstanceType<typeof RegistryError>).body).toEqual({
      kind: 'not-found',
      error: 'no file "nope.md" in the captured agent context; call context.list',
    })
  })
})
