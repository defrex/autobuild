import { expect, test } from 'bun:test'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { z } from 'zod'
import { documentSchema } from '../packages/core/src/config/reference-metadata'
import { renderFields, schemaFields } from '../packages/core/src/config/reference'
import {
  rewriteConfigurationReference,
  updateConfigurationReference,
} from './configuration-reference'

const document =
  'Prose before.\r\n\n<!-- configuration-reference:fixture -->\nstale\n<!-- configuration-reference:/fixture -->\nProse after.\n'
const region = { fixture: 'Generated fields.\n' }

test('write preserves prose, is idempotent, and check is exact-byte and read-only', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'configuration-reference-'))
  const path = join(directory, 'configuration.md')
  try {
    await writeFile(path, document)
    await expect(updateConfigurationReference(path, '--check', region)).rejects.toThrow(
      `Regenerate with bun run docs:configuration`,
    )
    expect(await readFile(path, 'utf8')).toBe(document)
    await updateConfigurationReference(path, '--write', region)
    const expected = rewriteConfigurationReference(document, region)
    expect(await readFile(path, 'utf8')).toBe(expected)
    expect(expected.startsWith('Prose before.\r\n\n')).toBe(true)
    expect(expected.endsWith('\nProse after.\n')).toBe(true)
    await updateConfigurationReference(path, '--write', region)
    expect(await readFile(path, 'utf8')).toBe(expected)
    await updateConfigurationReference(path, '--check', region)
    await expect(
      updateConfigurationReference(join(directory, 'missing'), '--check', region),
    ).rejects.toThrow('bun run docs:configuration')
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
})

test('marker errors are actionable; missing, duplicate, reversed, unknown and malformed regions fail', () => {
  for (const invalid of [
    'No markers',
    document + document,
    document.replace('/fixture', '/wrong'),
    document.replace('fixture -->', '/fixture -->'),
    document.replaceAll('fixture', 'unknown'),
    document.replace('fixture -->', 'fixture-->'),
    document.replace('<!-- configuration-reference:/fixture -->', ''),
  ])
    expect(() => rewriteConfigurationReference(invalid, region)).toThrow(/marker|region/i)
})

test('schema additions, removals, defaults and constraints cause check failure then regenerate successfully', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'configuration-drift-'))
  const path = join(directory, 'configuration.md')
  const doc = <T extends z.ZodType>(schema: T) =>
    documentSchema(schema, { description: 'Test description.' })
  const original = doc(z.strictObject({ name: doc(z.string().min(1).default('old')) }))
  const regionFor = (schema: z.ZodType) => ({
    fixture: renderFields(schemaFields(schema, 'fixture', () => 'test')),
  })
  try {
    const committed = rewriteConfigurationReference(document, regionFor(original))
    for (const schema of [
      doc(original.extend({ added: doc(z.boolean()) })),
      doc(original.omit({ name: true })),
      doc(z.strictObject({ name: doc(z.string().min(1).default('new')) })),
      doc(z.strictObject({ name: doc(z.string().min(2).default('old')) })),
    ]) {
      await writeFile(path, committed)
      await expect(
        updateConfigurationReference(path, '--check', regionFor(schema)),
      ).rejects.toThrow(path)
      expect(await readFile(path, 'utf8')).toBe(committed)
      await updateConfigurationReference(path, '--write', regionFor(schema))
      await updateConfigurationReference(path, '--check', regionFor(schema))
    }
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
})

test('package check guards generated bytes before public/reference parity', async () => {
  const { scripts } = await Bun.file(new URL('../package.json', import.meta.url)).json()
  expect(scripts['docs:configuration']).toBe('bun tools/configuration-reference.ts --write')
  expect(scripts.check).toContain('bun tools/configuration-reference.ts --check')
  expect(scripts.check.indexOf('configuration-reference.ts --check')).toBeLessThan(
    scripts.check.indexOf('docs-reference-sync.ts'),
  )
})

test('both modes reject missing descriptions with the full TOML path and no writes', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'configuration-metadata-'))
  const path = join(directory, 'configuration.md')
  try {
    await writeFile(path, document)
    for (const schema of [
      documentSchema(z.strictObject({ missing: z.string() }), { description: 'Root.' }),
      documentSchema(
        z.strictObject({
          nested: documentSchema(z.strictObject({ missing: z.string() }), {
            description: 'Nested.',
          }),
        }),
        { description: 'Root.' },
      ),
    ]) {
      const generate = () => ({
        fixture: renderFields(schemaFields(schema, 'fixture', () => 'test')),
      })
      for (const mode of ['--write', '--check'] as const) {
        await expect(updateConfigurationReference(path, mode, generate)).rejects.toThrow(
          /fixture\.(nested\.)?missing.*bun run docs:configuration/,
        )
        expect(await readFile(path, 'utf8')).toBe(document)
      }
    }
  } finally {
    await rm(directory, { recursive: true, force: true })
  }
})
